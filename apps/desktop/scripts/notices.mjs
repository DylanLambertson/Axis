// Generates THIRD-PARTY-NOTICES.txt from the repository's package-lock.json: every package the app ships (every
// lockfile package that is not dev-only, plus the Electron runtime), with its version, its declared licence and the
// full text of its licence and notice files. Two inclusions are checked, not assumed: Monaco's notices must carry the
// Apache-2.0 TypeScript compiler it bundles, and the Electron entry names the Chromium licence file that ships next
// to the app (scripts/bundle.mjs copies it from the runtime).
//   node scripts/notices.mjs --write   regenerate the file
//   node scripts/notices.mjs --check   exit 1 when the file is not what the lockfile gives
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = dirname(dirname(fileURLToPath(import.meta.url)));
export const repoRoot = join(appDir, "..", "..");
export const noticesFile = join(appDir, "THIRD-PARTY-NOTICES.txt");

/** Dev-only in the lockfile, but shipped: the Electron runtime is the app's executable. */
export const SHIPPED_DEV = new Set(["electron"]);
const LICENCE_FILE = /^(licen[cs]e|copying|notice|thirdpartynotices)([-.][a-z0-9]+)*$/i;

/** Text checks that must hold, by package name (a failing one stops the generator). */
export const REQUIRED = new Map([
  ["monaco-editor", [/typescript version \d/i, /Apache License\s+Version 2\.0/]],
]);

/** The shipped packages of a parsed lockfile (lockfileVersion 3), sorted by their path. */
export function shippedPackages(lock) {
  if (lock?.lockfileVersion !== 3 || typeof lock.packages !== "object") throw new Error("package-lock.json is not lockfile version 3");
  const out = [];
  for (const [path, entry] of Object.entries(lock.packages)) {
    if (!path.startsWith("node_modules/") || entry.link === true) continue;
    const name = entry.name ?? path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
    if (name.startsWith("@axis/")) continue;
    if (entry.dev === true && !SHIPPED_DEV.has(name)) continue;
    if (typeof entry.version !== "string") throw new Error(`${path}: no version in the lockfile`);
    out.push({ path, name, version: entry.version, license: typeof entry.license === "string" ? entry.license : "UNKNOWN" });
  }
  return out.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

const normalise = (text) => text.replace(/\r\n?/g, "\n").replace(/[ \t]+$/gm, "").trim();

/**
 * The notices text. `files(path)` lists the file names in an installed package directory; `read(path, file)` returns
 * one file's text. Throws when a package has no licence file or a required text is missing.
 */
export function renderNotices(packages, files, read) {
  const parts = [
    "Third-party software shipped with the desktop app",
    "",
    "Generated by apps/desktop/scripts/notices.mjs from package-lock.json; do not edit by hand.",
    "Each component keeps its own licence; the repository's LICENSE does not apply to them.",
  ];
  for (const pkg of packages) {
    const names = files(pkg.path).filter((f) => LICENCE_FILE.test(f)).sort();
    if (names.length === 0) throw new Error(`${pkg.name}@${pkg.version}: no licence file in ${pkg.path}`);
    const texts = names.map((f) => [f, normalise(read(pkg.path, f))]);
    for (const rule of REQUIRED.get(pkg.name) ?? []) {
      if (!texts.some(([, t]) => rule.test(t))) throw new Error(`${pkg.name}@${pkg.version}: its notices do not match ${rule}`);
    }
    parts.push("", "=".repeat(78), `${pkg.name} ${pkg.version} (${pkg.license})`, "=".repeat(78));
    if (pkg.name === "electron") {
      parts.push("", "The Electron runtime contains Chromium and its dependencies. Their licences are in", "LICENSES.chromium.html, which ships next to this file (copied from the Electron runtime).");
    }
    for (const [f, t] of texts) parts.push("", `--- ${f} ---`, "", t);
  }
  return `${parts.join("\n")}\n`;
}

export function generate(root = repoRoot) {
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
  return renderNotices(
    shippedPackages(lock),
    (path) => readdirSync(join(root, path), { withFileTypes: true }).filter((e) => e.isFile()).map((e) => e.name),
    (path, file) => readFileSync(join(root, path, file), "utf8"),
  );
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (mode !== "--write" && mode !== "--check") {
    process.stderr.write("usage: notices.mjs --write | --check\n");
    process.exit(2);
  }
  const text = generate();
  if (mode === "--write") writeFileSync(noticesFile, text);
  else if (readFileSync(noticesFile, "utf8") !== text) {
    process.stderr.write("THIRD-PARTY-NOTICES.txt is out of date; run `npm run notices --workspace @axis/desktop`\n");
    process.exit(1);
  }
}
