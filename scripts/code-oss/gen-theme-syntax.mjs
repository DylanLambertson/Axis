// Writes the syntax-colour snapshots of the Axis themes
// (code-oss/overlay/extensions/theme-axis/themes/axis-{dark,light}-syntax.json)
// by flattening the upstream include chains
//   2026-dark  -> dark_modern  -> dark_plus  -> dark_vs
//   2026-light -> light_modern -> light_plus -> light_vs
// from extensions/theme-defaults in the Code OSS tree. The merge follows the
// upstream loader (src/vs/workbench/services/themes/common/colorThemeData.ts,
// _loadColorTheme): included files first, tokenColors concatenated in order,
// semanticTokenColors merged with the including file winning.
//
// Usage: node scripts/code-oss/gen-theme-syntax.mjs [--check] [<code-oss tree>]
// The tree defaults to $AXIS_CODE_OSS_VENDOR_DIR/code-oss or vendor/code-oss.
// --check exits 1 when the committed snapshots differ (use after an upstream sync).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = path.join(repoRoot, 'code-oss/overlay/extensions/theme-axis/themes');

const args = process.argv.slice(2);
const check = args.includes('--check');
const positional = args.filter(a => !a.startsWith('--'));
const vendorDir = process.env.AXIS_CODE_OSS_VENDOR_DIR || path.join(repoRoot, 'vendor');
const tree = path.resolve(positional[0] || path.join(vendorDir, 'code-oss'));
const themesDir = path.join(tree, 'extensions/theme-defaults/themes');

/** Removes // and block comments outside strings and trailing commas, then parses. */
export function parseJsonc(text) {
	let out = '';
	let i = 0;
	let inString = false;
	while (i < text.length) {
		const c = text[i];
		if (inString) {
			out += c;
			if (c === '\\') {
				out += text[i + 1];
				i += 2;
				continue;
			}
			if (c === '"') {
				inString = false;
			}
			i++;
		} else if (c === '"') {
			inString = true;
			out += c;
			i++;
		} else if (c === '/' && text[i + 1] === '/') {
			while (i < text.length && text[i] !== '\n') {
				i++;
			}
		} else if (c === '/' && text[i + 1] === '*') {
			const end = text.indexOf('*/', i + 2);
			i = end === -1 ? text.length : end + 2;
		} else {
			out += c;
			i++;
		}
	}
	return JSON.parse(out.replace(/,(\s*[}\]])/g, '$1'));
}

function flatten(file, result) {
	const theme = parseJsonc(fs.readFileSync(file, 'utf8'));
	if (theme.include) {
		flatten(path.join(path.dirname(file), theme.include), result);
	}
	result.chain.push(path.basename(file));
	if (Array.isArray(theme.tokenColors)) {
		result.tokenColors.push(...theme.tokenColors);
	} else if (theme.tokenColors !== undefined) {
		throw new Error(`${file}: tokenColors is not an array; this generator does not handle tmTheme references`);
	}
	if (theme.semanticTokenColors) {
		Object.assign(result.semanticTokenColors, theme.semanticTokenColors);
	}
	result.semanticHighlighting = result.semanticHighlighting || theme.semanticHighlighting === true;
	return result;
}

function render(name, source) {
	const flat = flatten(path.join(themesDir, source), { chain: [], tokenColors: [], semanticTokenColors: {}, semanticHighlighting: false });
	const header = [
		`// Generated by scripts/code-oss/gen-theme-syntax.mjs. Do not edit by hand.`,
		`// Snapshot of the syntax colours of extensions/theme-defaults/themes/${source} at the pinned`,
		`// Code OSS commit, flattened from ${flat.chain.slice().reverse().join(' <- ')}.`,
		`// Source: Copyright (c) Microsoft Corporation. Licensed under the MIT License (LICENSE.txt).`,
	];
	const body = {
		$schema: 'vscode://schemas/color-theme',
		name,
		semanticHighlighting: flat.semanticHighlighting,
		tokenColors: flat.tokenColors,
		semanticTokenColors: flat.semanticTokenColors,
	};
	return header.join('\n') + '\n' + JSON.stringify(body, null, '\t') + '\n';
}

function main() {
	if (!fs.existsSync(themesDir)) {
		console.error(`error: ${themesDir} not found; run scripts/code-oss/fetch.sh or pass the Code OSS tree`);
		process.exit(2);
	}
	const outputs = [
		['axis-dark-syntax.json', render('Axis Dark (syntax)', '2026-dark.json')],
		['axis-light-syntax.json', render('Axis Light (syntax)', '2026-light.json')],
	];
	let stale = 0;
	for (const [file, content] of outputs) {
		const target = path.join(outDir, file);
		if (check) {
			const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
			if (current !== content) {
				console.error(`stale: ${path.relative(repoRoot, target)}`);
				stale++;
			}
		} else {
			fs.mkdirSync(outDir, { recursive: true });
			fs.writeFileSync(target, content);
			console.log(`wrote ${path.relative(repoRoot, target)}`);
		}
	}
	if (stale) {
		console.error(`${stale} snapshot(s) differ from upstream; rerun without --check and review the diff`);
		process.exit(1);
	}
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main();
}
